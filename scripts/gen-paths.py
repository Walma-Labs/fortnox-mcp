#!/usr/bin/env python3
"""Regenerate src/paths.ts from Fortnox's published OpenAPI document.

Fortnox serves its API reference as a Redoc page with the spec inlined. Usage:

    curl -sL https://apps.fortnox.se/apidocs -o apidocs.html
    python3 scripts/gen-paths.py apidocs.html > src/paths.ts
"""
import json
import re
import sys

# Endpoints the generic fortnox_get tool must never reach: GETs that SEND
# something (email, eprint, einvoice), return binary files, or belong to the
# bank and integration-developer programmes.
SKIP = re.compile(
    r"/(email|eprint|einvoice|print|printreminder|preview)$"
    r"|^/3/sie|^/api/bank-process|^/api/integration-developer"
    r"|^/3/archive/\{|^/3/inbox/\{|^/api/.*/content$|/csv$"
)

html = open(sys.argv[1], encoding="utf8").read()
start = html.index("__redoc_state = ") + len("__redoc_state = ")
state, _ = json.JSONDecoder().raw_decode(html[start:])
spec = state["spec"]["data"]

rows = [
    (path, (ops["get"].get("summary") or "").strip())
    for path, ops in sorted(spec["paths"].items())
    if "get" in ops and not SKIP.search(path)
]

print("// GENERATED by scripts/gen-paths.py from Fortnox's published OpenAPI document")
print("// (https://apps.fortnox.se/apidocs). Every read-only GET endpoint the generic")
print("// fortnox_get tool may call. Endpoints that send something (…/email, …/eprint,")
print("// …/einvoice), return files (print, preview, archive, inbox, SIE) or belong to")
print("// bank or integration-developer programmes are left out on purpose.")
print()
print("export const GET_PATHS: readonly (readonly [template: string, summary: string])[] = [")
for path, summary in rows:
    print(f"  [{json.dumps(path)}, {json.dumps(summary)}],")
print("];")
